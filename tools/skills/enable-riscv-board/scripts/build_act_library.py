#!/usr/bin/env python3
"""Build assets/act/udb_library.yaml for gen_act_config.py.

Records, for the UDB version ACT pins, every extension's ratified versions and
every parameter's definedBy condition, plus a default value taken from the
reviewed board configs (first config that sets it wins). Rerun when ACT moves
to a new UDB version or a reviewed board config changes.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

import yaml

SKILL_DIR = Path(__file__).resolve().parent.parent
DEFAULT_OUT = SKILL_DIR / "assets" / "act" / "udb_library.yaml"


def ratified_versions(ext: dict) -> list[str]:
    return [str(v["version"]) for v in ext.get("versions", []) if v.get("state") == "ratified"]


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--udb-spec", required=True, type=Path,
                   help="resolved spec dir, e.g. ~/.local/share/udb/0.1.17/gen/resolved_spec/_")
    p.add_argument("--udb-version", required=True)
    p.add_argument("--config", action="append", default=[], type=Path,
                   help="reviewed UDB board config to take defaults from (repeatable, priority order)")
    p.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = p.parse_args()

    extensions = {}
    for f in sorted((args.udb_spec / "ext").glob("*.yaml")):
        ext = yaml.safe_load(f.read_text())
        extensions[ext["name"]] = {"type": ext.get("type", "unknown"),
                                   "versions": [str(v["version"]) for v in ext.get("versions", [])],
                                   "ratified": ratified_versions(ext)}

    defaults: dict[str, tuple[object, str]] = {}
    for cfg in args.config:
        params = (yaml.safe_load(cfg.read_text()) or {}).get("params", {}) or {}
        for name, value in params.items():
            defaults.setdefault(name, (value, cfg.stem))

    params = {}
    for f in sorted((args.udb_spec / "param").glob("*.yaml")):
        prm = yaml.safe_load(f.read_text())
        entry = {"defined_by": prm["definedBy"], "schema": prm.get("schema", {})}
        if prm["name"] in defaults:
            entry["default"], entry["default_from"] = defaults[prm["name"]]
        params[prm["name"]] = entry

    unknown = sorted(set(defaults) - set(params))
    out = {"udb_version": args.udb_version, "default_sources": [c.stem for c in args.config],
           "extensions": extensions, "params": params}
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("# Generated by scripts/build_act_library.py; do not edit by hand.\n"
                        + yaml.safe_dump(out, sort_keys=True, width=120))
    print(f"wrote {args.out}: {len(extensions)} extensions, {len(params)} params, "
          f"{sum('default' in v for v in params.values())} with defaults")
    if unknown:
        print(f"warning: config params unknown to UDB {args.udb_version}: {', '.join(unknown)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
